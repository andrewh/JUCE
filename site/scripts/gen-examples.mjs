// Turns data/examples-meta.json (the curated picks) and the real files under ../examples
// into site pages under site/examples/, one per example, with every source file in a code
// group. VitePress highlights the code at build time, so nothing is fetched in the browser.
//
// The leading ISC licence comment is dropped from each file, because the pages note it once.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(here, '..', '..')
const outDir = join(here, '..', 'examples')
const dataFile = join(here, '..', 'data', 'examples.json')
const github = 'https://github.com/juce-framework/JUCE/tree/master'
const meta = JSON.parse(readFileSync(join(here, '..', 'data', 'examples-meta.json'), 'utf8'))

const langOf = (name) => (name.endsWith('.txt') || name.endsWith('.cmake') ? 'cmake' : 'cpp')
const stripLicence = (text) =>
  text.replace(/^\s*\/\*[\s\S]*?\*\/\s*\n/, (block) => (/ISC licen[cs]e/i.test(block) ? '' : block)).replace(/^\n+/, '')

rmSync(outDir, { recursive: true, force: true })
mkdirSync(outDir, { recursive: true })

const page = (p) => {
  const where = p.files.length === 1 ? `${p.path}/${p.files[0]}` : p.path
  const groups = p.files
    .map((f) => {
      const code = stripLicence(readFileSync(join(repoRoot, p.path, f), 'utf8')).replace(/\s+$/, '')
      return '````' + langOf(f) + ` [${f}]\n${code}\n` + '````'
    })
    .join('\n\n')
  return `---
title: ${p.name}
outline: false
---

# ${p.name}

**${p.blurb}**

${p.learn.map((l) => `- ${l.replace(/</g, "&lt;")}`).join('\n')}

Source: [${where}](${github}/${where}) on GitHub.

::: code-group

${groups}

:::
`
}

for (const p of meta.projects) writeFileSync(join(outDir, `${p.id}.md`), page(p))

const list = meta.cats
  .map((c) => {
    const items = meta.projects
      .filter((p) => p.cat === c)
      .map((p) => `- [${p.name}](./${p.id}): ${p.blurb}`)
      .join('\n')
    return `## ${c}\n\n${items}`
  })
  .join('\n\n')

writeFileSync(
  join(outDir, 'index.md'),
  `# Example browser

**${meta.projects.length} examples from the JUCE repository, grouped by what they teach, with the full source of every file.**

Pick an example, then switch between its files in the tabs. Each page links to the folder on GitHub. The leading ISC licence comment is left out of each file; the originals carry it, and the files are free to reuse under the ISC licence.

${list}
`
)

writeFileSync(
  dataFile,
  JSON.stringify(
    {
      note: 'Generated by scripts/gen-examples.mjs',
      groups: meta.cats.map((c) => ({
        text: c,
        items: meta.projects.filter((p) => p.cat === c).map((p) => ({ text: p.name, link: `/examples/${p.id}` }))
      }))
    },
    null,
    2
  ) + '\n'
)
