// Turns ../docs/tutorials/*.md (the condensed tutorials, readable on GitHub) into site pages
// under site/tutorials/, and writes data/tutorials.json for the sidebar.
//
// The Markdown in docs/tutorials stays the only source. This script rewrites what a plain
// GitHub view and the site treat differently:
//   - links that leave docs/tutorials (examples, BREAKING_CHANGES.md, ...) become GitHub URLs
//   - README.md and NOTICE.md become index.md and notice.md
//   - the first sentence under the title is bolded, matching the other pages
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, normalize, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(here, '..', '..')
const srcDir = join(repoRoot, 'docs', 'tutorials')
const outDir = join(here, '..', 'tutorials')
const dataFile = join(here, '..', 'data', 'tutorials.json')
const github = 'https://github.com/juce-framework/JUCE'

// Short sidebar labels. A guide missing from this list falls back to its title.
const labels = {
  '01-getting-started': 'Getting started',
  '02-graphics-and-layout': 'Graphics and layout',
  '03-widgets': 'Widgets',
  '04-listeners-and-state': 'Listeners, ValueTree, and undo',
  '05-audio-io-and-playback': 'Audio I/O and playback',
  '06-synthesis': 'Synthesis',
  '07-midi-and-mpe': 'MIDI and MPE',
  '08-plugin-basics': 'Plug-in basics',
  '09-plugin-parameters': 'Parameters and state',
  '10-audio-processor-graph': 'AudioProcessorGraph',
  '11-dsp': 'DSP',
  '12-utilities': 'Core utilities',
  '13-opengl': 'OpenGL',
  '14-mobile-and-app-services': 'Mobile and app services',
  '15-physics-music': 'Physics as an instrument',
  '16-box2d-v3': 'Box2D v3',
  '17-modal-physics-audio': 'Modal physics audio'
}

if (!existsSync(srcDir)) throw new Error(`No tutorials found at ${srcDir}`)

const rename = { 'README.md': 'index.md', 'NOTICE.md': 'notice.md' }

// Link targets that leave the tutorials folder, resolved against the repository.
const rewriteLink = (target) => {
  const [rawPath, hash = ''] = target.split('#')
  if (!rawPath || /^[a-z]+:/i.test(rawPath)) return target
  const path = decodeURIComponent(rawPath)

  if (!path.startsWith('..')) {
    const base = path.replace(/^\.\//, '')
    return (rename[base] ? `./${rename[base]}` : target)
  }

  const repoPath = normalize(join('docs', 'tutorials', path)).split('\\').join('/')
  const abs = join(repoRoot, repoPath)
  const kind = existsSync(abs) && statSync(abs).isDirectory() ? 'tree' : 'blob'
  const encoded = repoPath.split('/').map(encodeURIComponent).join('/')
  return `${github}/${kind}/master/${encoded}${hash ? `#${hash}` : ''}`
}

const transform = (name, text) => {
  let out = text.replace(/\]\(([^)]+)\)/g, (_, target) => `](${rewriteLink(target)})`)

  // "See [NOTICE.md](./notice.md)" reads better as a phrase on a web page.
  out = out.replace(/\[NOTICE\.md\]\(\.\/notice\.md\)/g, '[the attribution notice](./notice.md)')

  // Bold the first sentence under the title, as every other page does.
  out = out.replace(/^(# .+\n\n)(?!\*\*)([\s\S]+?\.)(\s)/m, (_, head, sentence, tail) => `${head}**${sentence}**${tail}`)

  if (name === 'README.md') {
    out = out.replace(/^# JUCE tutorials, condensed/m, '# Tutorials')
  }
  return out
}

rmSync(outDir, { recursive: true, force: true })
mkdirSync(outDir, { recursive: true })

const guides = []
for (const file of readdirSync(srcDir).filter((f) => f.endsWith('.md')).sort()) {
  const text = readFileSync(join(srcDir, file), 'utf8')
  const outName = rename[file] ?? file
  writeFileSync(join(outDir, outName), transform(file, text))

  const slug = file.replace(/\.md$/, '')
  if (/^\d\d-/.test(file)) {
    const title = text.match(/^# (.+)$/m)?.[1] ?? slug
    guides.push({ slug, label: labels[slug] ?? title, title })
  }
}

writeFileSync(dataFile, JSON.stringify({ note: 'Generated by scripts/gen-tutorials.mjs', guides }, null, 2) + '\n')
console.log(`Wrote ${guides.length} tutorial guides to ${relative(repoRoot, outDir)}`)
