// Copies the built site from .vitepress/dist into ../docs for GitHub Pages.
//
// ../docs also holds upstream JUCE files (CMake API.md, doxygen/, ...), so this
// never wipes the folder. Instead it records every file it writes in
// docs/.site-manifest.json, removes only the files listed from the previous run,
// and refuses to overwrite anything it did not create.
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, rmdirSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const distDir = join(here, '..', '.vitepress', 'dist')
const docsDir = join(here, '..', '..', 'docs')
const manifestFile = join(docsDir, '.site-manifest.json')

if (!existsSync(distDir)) throw new Error('No build output found. Run "npm run build" first.')

const walk = (dir) =>
  readdirSync(dir).flatMap((name) => {
    const full = join(dir, name)
    return statSync(full).isDirectory() ? walk(full) : [full]
  })

const previous = existsSync(manifestFile) ? JSON.parse(readFileSync(manifestFile, 'utf8')).files : []
// The Doxygen API reference (api/) is ~150 MB, so CI publishes it and it is never committed to docs/.
const skip = (f) => f === 'api' || f.startsWith('api/')
const next = walk(distDir).map((f) => relative(distDir, f).split('\\').join('/')).filter((f) => !skip(f))
next.push('.nojekyll')

const clashes = next.filter((f) => existsSync(join(docsDir, f)) && !previous.includes(f))
if (clashes.length) {
  throw new Error(`Refusing to overwrite files the site did not create:\n  ${clashes.join('\n  ')}`)
}

// Remove the previous build, then tidy up any directories it leaves empty.
for (const f of previous) rmSync(join(docsDir, f), { force: true })
const pruneEmpty = (dir) => {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name)
    if (statSync(full).isDirectory()) pruneEmpty(full)
  }
  if (dir !== docsDir && readdirSync(dir).length === 0) rmdirSync(dir)
}
pruneEmpty(docsDir)

mkdirSync(docsDir, { recursive: true })
cpSync(distDir, docsDir, { recursive: true, filter: (src) => !skip(relative(distDir, src).split('\\').join('/')) })
writeFileSync(join(docsDir, '.nojekyll'), '')
writeFileSync(manifestFile, JSON.stringify({ note: 'Files generated by site/scripts/publish.mjs', files: next.sort() }, null, 2) + '\n')

console.log(`Published ${next.length} files to ${docsDir} (removed ${previous.length} from the previous build).`)
